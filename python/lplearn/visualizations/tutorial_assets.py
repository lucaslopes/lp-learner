@dataclass
class BuildResult:
    written: list[str] = field(default_factory=list)
    failed: dict[str, str] = field(default_factory=dict)


def _write_text(path: Path, text: str) -> None:
    atomic_write_text(path, text)


def build_assets(cfg: Mapping[str, Any]) -> tuple[BuildResult, dict[str, Any]]:
    '''
    Draw every figure, write every table and numbers.tex. Returns what was written or failed, and a manifest.
    '''

    results_root = Path(cfg.get('results_root', 'results'))
    commons_dir = results_root / str(cfg.get('commons_summary_dir', 'commons/summary_tutorial'))
    finite_n_summary = results_root / str(cfg.get('finite_n_summary', 'finite_n/summary/finite_n_summary.csv'))
    learned_solutions = results_root / str(cfg.get('learned_solutions', 'learners/summary/solutions_K5T10.npz'))
    figure_dir = Path(cfg.get('figure_dir', results_root / 'tutorial' / 'figures'))
    table_dir = Path(cfg.get('table_dir', results_root / 'tutorial' / 'tables'))
    figures = list(cfg.get('figures', FIGURES))
    tables = list(cfg.get('tables', TABLES))
    unknown = [f for f in figures if f not in FIGURES] + [t for t in tables if t not in TABLES]
    if unknown:
        raise ValueError(f'unknown tutorial asset(s): {unknown}')

    write_numbers = cfg.get('write_numbers', True)
    if not isinstance(write_numbers, bool):
        raise ValueError('write_numbers must be a boolean')
    needs_data = write_numbers or bool(set(figures) & {'tutorial_overload', 'tutorial_costs'}) or any(t != 'parameters' for t in tables)
    data = None
    data_error = None
    if needs_data:
        try:
            data = load_data(commons_dir, finite_n_summary)
        except (TutorialInputError, ValueError, OSError) as exc:
            data_error = f'{type(exc).__name__}: {exc}'
    tm = solve_tutorial_model(base_params(cfg.get('model', {})))
    inputs = dict(data.files) if data is not None else {}
    if 'tutorial_learned' in figures and learned_solutions.is_file():
        inputs[str(learned_solutions)] = _sha256(learned_solutions)
    runs = plaza_runs(tm, seed=int(cfg.get('run_seed', 2026))) if write_numbers or 'tutorial_run' in figures else {}
    result = BuildResult()
    drawers = {
        'tutorial_kernel': lambda path: plot_kernel(tm, path),
        'tutorial_values': lambda path: plot_values(tm, path),
        'tutorial_policies': lambda path: plot_policies(tm, path),
        'tutorial_pies': lambda path: plot_pies(tm, path),
        'tutorial_prices': lambda path: plot_prices(tm, path),
        'tutorial_learned': lambda path: plot_learned(tm, learned_solutions, path),
        'tutorial_overload': lambda path: plot_overload(data, path),
        'tutorial_costs': lambda path: plot_costs(tm, data, path),
        'tutorial_run': lambda path: plot_run(tm, runs, path),
    }
    for name in figures:
        if name in {'tutorial_overload', 'tutorial_costs'} and data_error:
            result.failed[name] = data_error
            continue
        try:
            drawers[name](figure_dir / f'{name}.pdf')
            result.written.append(str(figure_dir / f'{name}.pdf'))
        except (TutorialInputError, KeyError, ValueError) as exc:
            result.failed[name] = f'{type(exc).__name__}: {exc}'
    writers = {
        'parameters': lambda: table_parameters(tm),
        'results_main': lambda: table_results_main(data),
        'results_detail': lambda: table_results_detail(tm, data),
        'dilemma': lambda: table_dilemma(data),
        'whatif': lambda: table_whatif(data),
        'coordinators': lambda: table_coordinators(data),
        'sensitivity': lambda: table_sensitivity(data),
    }
    for name in tables:
        if name != 'parameters' and data_error:
            result.failed[name] = data_error
            continue
        try:
            _write_text(table_dir / f'{name}.tex', writers[name]())
            result.written.append(str(table_dir / f'{name}.tex'))
        except (TutorialInputError, KeyError, ValueError) as exc:
            result.failed[name] = f'{type(exc).__name__}: {exc}'
    values = {}
    if write_numbers:
        if data_error:
            result.failed['numbers'] = data_error
        else:
            try:
                values = numbers(tm, data)
                values.update(run_numbers(tm, runs))
                _write_text(table_dir / 'numbers.tex', numbers_tex(values))
                result.written.append(str(table_dir / 'numbers.tex'))
            except (TutorialInputError, KeyError, ValueError) as exc:
                values = {}
                result.failed['numbers'] = f'{type(exc).__name__}: {exc}'
    manifest = {
        'model': tm.params.to_dict(),
        'lp_value': float(tm.lp['objective']),
        'lp_solver': tm.lp['solver'],
        'inputs': inputs,
        'phase': 'complete' if not result.failed else 'partial',
        'write_numbers': write_numbers,
        'written': result.written,
        'failed': result.failed,
        'numbers': values,
    }
    return result, manifest
