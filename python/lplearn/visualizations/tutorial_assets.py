def _macro_name(name: str) -> str:
    if not name.isalpha():
        raise ValueError(f'macro names must be letters only, got {name!r}')
    return 'tn' + name


def numbers(tm: TutorialModel, data: TutorialData) -> dict[str, str]:
    '''
    Every number the tutorial's text quotes, keyed by a letters-only name (the macro is \\tn<name>).
    '''

    p = tm.params
    K, T = p.K, p.T
    out: dict[str, str] = {}
    words = {10: 'Ten', 100: 'Hundred', 1000: 'Thousand'}

    # Model
    out['RLow'] = _f(per_period_departure_probability(p.p, p.b_low), 3)
    out['RHigh'] = _f(per_period_departure_probability(p.p, p.b_high), 3)
    out['RLowPct'] = _f(100 * per_period_departure_probability(p.p, p.b_low), 1)
    out['RHighPct'] = _f(100 * per_period_departure_probability(p.p, p.b_high), 1)
    out['MeanMinutes'] = _f(1.0 / p.p, 2)
    out['StaffLow'] = _f(2 * (1 + p.b_low), 2)
    out['StaffHigh'] = _f(2 * (1 + p.b_high), 2)
    out['StaffDiff'] = _f(2 * (p.b_high - p.b_low), 2)
    low = transition_kernel('CJS', K, p.p, p.b_low)
    high = transition_kernel('CJS', K, p.p, p.b_high)
    out['KernelLowStay'] = _f(low[1, 3, 4], 2)    # 3 cars + 1 admitted, nobody leaves
    out['KernelHighStay'] = _f(high[1, 3, 4], 2)
    out['KernelHighOneLeaves'] = _f(high[1, 3, 3], 2)
    out['KernelFullLowStay'] = _f(low[0, K, K], 2)
    out['KernelFullHighStay'] = _f(high[0, K, K], 2)
    out['UnavoidableLost'] = _f((1 - p.alpha) * p.T * p.gamma, 0)
    out['CarsPerBooth'] = _f(p.alpha * T, 1)
    out['JointStatesExp'] = f'{int(math.floor(1000 * math.log10(K + 1)))}'
    out['LPVariables'] = f'{T * (K + 1) * 4}'

    # LP and selfish policy
    lam = np.asarray(tm.lp['lam_res'], dtype=float)
    out['LPValue'] = _f(tm.lp['objective'], 2)
    out['LPValueShort'] = _f(tm.lp['objective'], 1)
    out['PriceAttMax'] = _f(lam[1].max(), 0)
    out['PriceAttFirst'] = _f(lam[1, 0], 0)
    out['PriceCarFirst'] = _f(lam[0, 0], 1)
    out['PriceAttPeakStage'] = f'{int(np.argmax(lam[1]))}'
    out['PriceCarZeroFrom'] = f'{int(np.flatnonzero(lam[0] < 1e-6)[0])}' if np.any(lam[0] < 1e-6) else '--'
    sol = tm.selfish
    adm = sol.admit_advantage()
    fast = sol.fast_advantage()
    out['GainCarMax'] = _f(np.max(adm[:, :K, :]), 0)
    reachable = np.arange(K + 1)[None, :] <= np.arange(T)[:, None]  # (T, S): at most t cars at period t
    out['GainAttMax'] = _f(np.max(np.where(reachable[:, :, None], fast, -np.inf)), 0)
    out['SelfishAttAllUntil'] = f'{int(np.max([t for t in range(T) if np.all(sol.b[t] == 1)]))}' if np.any(np.all(sol.b == 1, axis=1)) else '--'
    out['LastStageAttCost'] = _f(-np.max(fast[T - 1]), 2)
    out['SelfishAttAllPeriods'] = f'{int(out["SelfishAttAllUntil"]) + 1}' if out['SelfishAttAllUntil'] != '--' else '--'
    out['GainAttEmpty'] = _f(fast[4, 0, 1], 1)   # attendant gain at period 4, gate open, empty lane
    out['GainAttFour'] = _f(fast[4, 4, 1], 1)    # same with 4 cars (reachable at period 4)

    # Fluid
    fl_lp, fl_s1, fl_s2 = tm.fluid['lp'], tm.fluid['selfish_M1'], tm.fluid['selfish_M2']
    out['FluidSelfishRation'] = _f(fl_s1['cost'], 1)
    out['FluidSelfishCong'] = _f(fl_s2['cost'], 1)
    out['FluidGapRationPct'] = _f(100 * (fl_s1['cost'] / tm.lp['objective'] - 1), 1)
    lost_lp, lost_s1 = fluid_lost_cars(tm, 'lp'), fluid_lost_cars(tm, 'selfish_M1')
    first_lp = int(np.flatnonzero(lost_lp > 1e-6)[0])
    first_s1 = int(np.flatnonzero(lost_s1 > 1e-6)[0])
    out['FluidFirstLossLP'] = f'{first_lp}'
    out['FluidFirstLossSelfish'] = f'{first_s1}'
    out['FluidLostLPUpTo'] = _f(np.sum(lost_lp[:first_lp + 1]), 2)
    out['FluidLostSelfishUpTo'] = _f(np.sum(lost_s1[:first_lp + 1]), 2)
    out['FluidLostLP'] = _f(np.sum(lost_lp), 2)
    out['FluidLostSelfish'] = _f(np.sum(lost_s1), 2)

    # Simulation: main comparison
    for N in (10, 100, 1000):
        w = words[N]
        coord = pop_row(data, 'coord', 'M1', N)
        out[f'Coord{w}'] = _f(coord['cost_mean'], 1)
        out[f'CoordGapLP{w}'] = _f(100 * (coord['cost_mean'] / tm.lp['objective'] - 1), 1)
        for mech, mw in (('M1', 'Ration'), ('M2', 'Cong')):
            sel = pop_row(data, 'selfish', mech, N)
            pr = paired_row(data, 'selfish_minus_coord', mech, N)
            out[f'Selfish{mw}{w}'] = _f(sel['cost_mean'], 1)
            out[f'Gap{mw}{w}'] = _f(pr['diff_mean'], 1)
            out[f'Gap{mw}CI{w}'] = _f(pr['diff_ci95'], 1)
            out[f'Gap{mw}Pct{w}'] = _f(pr['pct_of_coord'], 1)
    sel1 = pop_row(data, 'selfish', 'M1', 1000)
    coord = pop_row(data, 'coord', 'M1', 1000)
    out['OverFastSelfish'] = _pct(sel1['overload_fast'], 0)
    out['OverAdmSelfish'] = _pct(sel1['overload_admit'], 0)
    out['ReqFastRatio'] = _f(sel1['requested_fast'] / p.beta, 1)
    out['ReqAdmRatio'] = _f(sel1['requested_admit'] / p.alpha, 2)
    out['FullSelfish'] = _pct(sel1['full_mean_per_stage'], 1)
    out['FullCoord'] = _pct(coord['full_mean_per_stage'], 1)
    out['LostSelfish'] = _f(lost_cars(sel1, p), 2)
    out['LostCoord'] = _f(lost_cars(coord, p), 2)
    out['LostSelfishPct'] = _f(100 * lost_cars(sel1, p) / (p.alpha * T), 1)
    out['LostCoordPct'] = _f(100 * lost_cars(coord, p) / (p.alpha * T), 1)
    out['LostExtraPct'] = _f(100 * (lost_cars(sel1, p) / lost_cars(coord, p) - 1), 0)
    out['LostGapCost'] = _f(p.gamma * (lost_cars(sel1, p) - lost_cars(coord, p)), 1)
    out['LostDiff'] = _f(lost_cars(sel1, p) - lost_cars(coord, p), 2)
    m0 = paired_row(data, 'selfish_minus_coord', 'M0', 1000)
    out['NoEnforcePct'] = _f(-m0['pct_of_coord'], 0)
    out['NoEnforceFastRatio'] = _f(pop_row(data, 'selfish', 'M0', 1000)['used_fast'] / p.beta, 1)

    # Social dilemma
    for (label, test), name in zip(DEVIATION_TESTS, ('NeverFast', 'FollowLP', 'NeverAdmit')):
        row = dilemma_row(data, test, 'M1', 1000)
        out[f'Dev{name}'] = _f(row['diff_mean'], 0)
        out[f'Dev{name}CI'] = _f(row['diff_ci95'], 0)
    for mech, mw in (('M1', 'Ration'), ('M2', 'Cong')):
        br = dilemma_row(data, 'verdict: individual (fluid best response to the selfish lotteries)', mech, 1000)
        if str(br['verdict']) != 'selfish rule is a best response':
            raise TutorialInputError(f'the text states that the selfish rule is a best response under {mech}; the summary says {br["verdict"]!r}')
        verdict = dilemma_row(data, 'verdict: social dilemma (collective worse and individual rational)', mech, 1000)
        out[f'Dilemma{mw}'] = str(verdict['verdict'])

    # Price-taking
    price = pop_row(data, 'price', 'M1', 1000)
    pp = paired_row(data, 'price_minus_coord', 'M1', 1000)
    out['PriceCost'] = _f(price['cost_mean'], 1)
    out['PricePct'] = _f(pp['pct_of_coord'], 1)
    out['PriceReqFast'] = _pct(price['requested_fast'], 0)
    out['LostPrice'] = _f(lost_cars(price, p), 2)
    for tie, name in (('no_request', 'NoReq'), ('request', 'Req')):
        sol_p = priced_solution(tm.model, tm.lp['lam_res'], tie)
        fl_p = fluid_mechanism(p, tm.model, deterministic_policy(sol_p.u), 'M1')
        out[f'PriceFluid{name}'] = _f(fl_p['cost'], 1)
        out[f'PriceFluid{name}Pct'] = _f(100 * (fl_p['cost'] / tm.lp['objective'] - 1), 1)
        if tie == 'no_request':
            refused = [t for t in range(T) if fl_p['requested'][0, t] < 1e-9]
            out['PriceRefusedPeriods'] = (', '.join(str(t) for t in refused[:-1]) + ' and ' + str(refused[-1])) if len(refused) > 1 else (str(refused[0]) if refused else '--')
            out['PriceRefusedCount'] = f'{len(refused)}'
            out['PriceRefusedLost'] = _f(p.alpha * len(refused), 2)
            out['PriceTiesFirst'] = f'{int(sol_p.n_minimisers[0, 0])}'
            out['PriceFluidAttRequests'] = _f(float(fl_p['requested'][1].sum()), 2)

    # What-if
    for scenario, name in (('beta=1.00', 'AllAtt'), ('alpha=1.00', 'AllCars')):
        for mech, mw in (('M1', 'Ration'), ('M2', 'Cong')):
            pr = paired_row(data, 'selfish_minus_coord', mech, 1000, scenario=scenario)
            out[f'WhatIf{name}{mw}'] = _signed(pr['pct_of_coord'], 1)
            out[f'WhatIf{name}{mw}Abs'] = _f(abs(pr['pct_of_coord']), 1)
    fl = data.fluid
    lp_all_att = _one(fl, 'commons_fluid', scenario='beta=1.00', case='CJS', mechanism='M1', tie_break='no_request')
    out['WhatIfAllAttLP'] = _f(lp_all_att['lp_value'], 1)
    coord_all_att = pop_row(data, 'coord', 'M1', 1000, scenario='beta=1.00')
    sel_all_att = pop_row(data, 'selfish', 'M1', 1000, scenario='beta=1.00')
    out['WhatIfAllAttCoord'] = _f(coord_all_att['cost_mean'], 1)
    out['WhatIfAllAttSelfish'] = _f(sel_all_att['cost_mean'], 1)
    out['WhatIfAllAttCoordGapLP'] = _f(100 * (coord_all_att['cost_mean'] / lp_all_att['lp_value'] - 1), 1)
    out['WhatIfAllAttFullSelfish'] = _pct(sel_all_att['full_mean_per_stage'], 0)
    out['WhatIfAllAttOverAdm'] = _pct(sel_all_att['overload_admit'], 0)
    out['FullSelfishRound'] = _pct(sel1['full_mean_per_stage'], 0)
    for scenario, name in (('beta=1.00', 'AllAtt'), ('alpha=1.00', 'AllCars')):
        for mech, mw in (('M1', 'Ration'), ('M2', 'Cong')):
            verdict = dilemma_row(data, 'verdict: social dilemma (collective worse and individual rational)', mech, 1000, scenario=scenario)
            out[f'WhatIf{name}Dilemma{mw}'] = str(verdict['verdict'])

    # Sensitivity
    for scenario, name in (('beta=0.10', 'BetaLow'), ('beta=0.50', 'BetaHigh')):
        pr = paired_row(data, 'selfish_minus_coord', 'M1', 100, scenario=scenario)
        out[f'Sens{name}'] = _f(pr['pct_of_coord'], 1)
    pr = paired_row(data, 'selfish_minus_coord', 'M1', 1000, tie_break='request')
    out['SensTieRequest'] = _f(pr['pct_of_coord'], 1)

    # Coordinators (finite_n stage)
    lp_value = float(finite_n_row(data, 'A', 'projection', 1000)['lp_objective'])
    for method, policy, name in (('A', 'projection', 'Proj'), ('A', 'lp_update', 'Update'), ('C', 'projection', 'GDA'),
                                 ('D', 'projection', 'SGDA')):
        for N in (10, 100, 1000):
            row = finite_n_row(data, method, policy, N)
            gap = 100 * (float(row['cost_mean']) - lp_value) / lp_value
            out[f'Coord{name}Gap{words[N]}'] = _f(gap, _pct_digits(gap))
    for method, name in (('A', 'LP'), ('C', 'GDA'), ('D', 'SGDA')):
        row = finite_n_row(data, method, 'projection', 1000)
        out[f'Repairs{name}'] = _pct(row['repairs_frac'], 1 if method != 'A' else 2)
    out['GDAMassFinal'] = _f(finite_n_row(data, 'C', 'projection', 1000)['source_mass_final'], 2)
    out['GDACostBelowPct'] = _f(100 * (1 - float(finite_n_row(data, 'C', 'projection', 1000)['source_objective']) / lp_value), 0)
    out['CoordTableMaxCI'] = _f(max(float(finite_n_row(data, m_, pol, N)['cost_ci95'])
                                    for m_, pol, _ in COORDINATORS for N in (10, 100, 1000)), 1)
    hyper_iters, hyper_samples = 2_000_000, 10
    out['SGDASamples'] = f'{hyper_iters * (K + 1) * 4 * hyper_samples:.1e}'.replace('e+0', '\\times10^{').replace('e+', '\\times10^{') + '}'
    indep = finite_n_row(data, 'A', 'independent', 1000)
    out['IndepOverMax'] = _pct(indep['over_max'], 1)
    out['IndepOverReps'] = _pct(indep['over_rep_frac'], 0)
    indep10 = finite_n_row(data, 'A', 'independent', 10)
    out['IndepOverMaxTen'] = _pct(indep10['over_max'], 0)
    return out


def run_numbers(tm: TutorialModel, runs: Mapping[str, RunRecord]) -> dict[str, str]:
    '''Numbers quoted about the illustrative run and the single-booth values.'''
    p = tm.params
    out = {'RunN': f'{runs["coord"].states.shape[1]}', 'RunCars': f'{int(math.floor(p.alpha * runs["coord"].states.shape[1] + 1e-9))}',
           'RunAtts': f'{int(math.floor(p.beta * runs["coord"].states.shape[1] + 1e-9))}'}
    for key, name in (('coord', 'Coord'), ('selfish', 'Selfish')):
        run = runs[key]
        out[f'Run{name}Cost'] = _f(run.cost.sum(axis=0).mean(), 1)
        out[f'Run{name}Missed'] = f'{int(run.missed.sum())}'
        out[f'Run{name}Full'] = f'{int((run.states == p.K).sum())}'
    sol = tm.selfish
    out['SelfishValueStart'] = _f(sol.V[0, 0], 1)
    return out


def numbers_tex(values: Mapping[str, str]) -> str:
    lines = [HEADER.rstrip(), '% Numbers quoted in the text of papers/Tutorial/main.tex, one macro per number.']
    for name in sorted(values):
        lines.append(f'\\newcommand{{\\{_macro_name(name)}}}{{{values[name]}}}')
    return '\n'.join(lines) + '\n'


