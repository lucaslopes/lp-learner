def load_learned(path: str | Path, method: str, field_name: str = 'y_avg') -> dict[int, np.ndarray]:
    '''Arrays `field_name` of every recorded seed of a learned method (CJS, K = 5, T = 10), keyed by seed.'''
    path = Path(path)
    if not path.is_file():
        raise TutorialInputError(f'missing input {path}; run and summarize the learners stage first')
    data = np.load(path)
    prefix = f'CJS/{method}/seed'
    out = {}
    for key in data.files:
        if key.startswith(prefix) and key.endswith(f'/{field_name}'):
            out[int(key[len(prefix):].split('/')[0])] = np.asarray(data[key], dtype=float)
    if not out:
        raise TutorialInputError(f'{path}: no {field_name} arrays for method {method}')
    return dict(sorted(out.items()))


