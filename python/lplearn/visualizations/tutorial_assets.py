@dataclass
class RunRecord:
    '''One simulated run: per period and booth, the lane length, the realised actions and the cost.'''

    states: np.ndarray   # (T, N)
    a: np.ndarray        # (T, N) realised gate decision
    b: np.ndarray        # (T, N) realised attendant
    cost: np.ndarray     # (T, N) one-period cost
    K: int               # lane capacity

    @property
    def missed(self) -> np.ndarray:
        '''Booth-periods without a new car (gate closed, or open on a full lane).'''
        return (self.a == 0) | (self.states == self.K)


def simulate_run(tm: TutorialModel, controller: Any, mechanism_name: str, N: int, replication: int, seed: int) -> RunRecord:
    '''
    One replication of N booths, with the random-number keys of ``lplearn.commons.experiment`` ([seed, r, k]: 0
    transitions, 1 controller, 2 lotteries, 3 initial states), recording every booth.
    '''

    m, p = tm.model, tm.params
    T, S, K = m.T, m.S, p.K
    game = Game(p, m, np.asarray(tm.lp['lam_res'], dtype=float))
    mechanism = make_mechanism(mechanism_name, p.b_low, p.b_high)
    caps = capacities(N, p.alpha, p.beta)
    uniforms = np.random.default_rng([seed, replication, 0]).random((T, N))
    cdf_init = np.cumsum(m.m0)
    cdf_init[-1] = 1.0
    x_init = np.random.default_rng([seed, replication, 3]).random(N)
    states = np.minimum(np.searchsorted(cdf_init, x_init, side='right'), S - 1).astype(np.int64)
    rng_c = np.random.default_rng([seed, replication, 1])
    controller.reset(N, rng_c)
    rng_m = np.random.default_rng([seed, replication, 2])
    rec = {k: np.zeros((T, N), dtype=np.int64) for k in ('states', 'a', 'b')}
    cost = np.zeros((T, N))
    for t in range(T):
        a_req, b_req = controller.act(t, states, rng_c)
        a, b, info = mechanism.apply(t, states, np.asarray(a_req, dtype=np.int8), np.asarray(b_req, dtype=np.int8), caps, rng_m)
        u = 2 * a.astype(np.int64) + b.astype(np.int64)
        rec['states'][t], rec['a'][t], rec['b'][t] = states, a, b
        cost[t] = m.c[states, u]
        if t < T - 1:
            low, high = game.cdf(info['q_high'])
            rows = np.where(b[:, None] == 1, high[a, states], low[a, states])
            states = np.minimum((uniforms[t][:, None] >= rows).sum(axis=1), K).astype(np.int64)
    return RunRecord(states=rec['states'], a=rec['a'], b=rec['b'], cost=cost, K=K)


def plaza_runs(tm: TutorialModel, *, N: int = RUN_N, replication: int = RUN_REPLICATION, seed: int = 2026) -> dict[str, RunRecord]:
    '''The coordinator and the selfish booths (rationing) on the same random numbers.'''
    sol = tm.selfish
    coord = LPProjectionController(tm.pi_lp, tm.model.budgets, rounding='randomized')
    selfish = TableController(sol.a.astype(np.int8), sol.b.astype(np.int8))
    return {'coord': simulate_run(tm, coord, 'M1', N, replication, seed),
            'selfish': simulate_run(tm, selfish, 'M1', N, replication, seed)}


