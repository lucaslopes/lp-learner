def plot_kernel(tm: TutorialModel, out_path: str | Path | None = None, *, figsize=(6.6, 2.3)) -> Figure:
    '''
    Where a lane goes in one period, for normal and fast service: next-state distributions from 3 cars with the gate
    open (4 cars to serve) and from a full lane.
    '''

    p = tm.params
    S = p.K + 1
    low = transition_kernel('CJS', p.K, p.p, p.b_low)
    high = transition_kernel('CJS', p.K, p.p, p.b_high)
