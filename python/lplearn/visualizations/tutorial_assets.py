def plot_overload(data: TutorialData, out_path: str | Path | None = None, *, N: int = 1000, mechanism: str = 'M1',
                  figsize=(6.6, 2.4)) -> Figure:
    '''
    Requests divided by supply, period by period (simulation, N booths, 95% intervals): cars (left) and attendants
    (right), for the selfish booths and the coordinator.
    '''

    st = data.stages
    sub = st[(st['scenario'] == 'base') & (st['case'] == 'CJS') & (st['N'] == N) & (st['mechanism'] == mechanism)
             & (st['tie_break'] == 'no_request')]
    if sub.empty:
        raise TutorialInputError(f'commons_stages: no rows for N={N}, {mechanism}')
    panels = (('ratio_admission', 'Cars: requests / cars in the platoon'), ('ratio_high_rate', 'Attendants: requests / attendants'))
    labels = {'coord': 'coordinator', 'selfish': 'selfish booths'}
    with rc_context(PAPER_RC):
        fig = Figure(figsize=figsize, layout='constrained')
        axes = fig.subplots(1, 2)
        for ax, (metric, title) in zip(axes, panels):
            for pop, color in (('coord', COORD_COLOR), ('selfish', SELFISH_COLOR)):
                part = sub[(sub['population'] == pop) & (sub['metric'] == metric)].sort_values('stage')
                if part.empty:
                    raise TutorialInputError(f'commons_stages: no {metric} rows for {pop}')
                ax.plot(part['stage'], part['mean'], color=color, marker='o', ms=3, lw=1.2)
                ax.fill_between(part['stage'], part['ci_low'], part['ci_high'], color=color, alpha=0.18, lw=0)
            ax.axhline(1.0, color='black', ls=':', lw=0.9)
            ax.set_title(title, fontsize=9, pad=3)
            ax.set_xlabel('period $t$', fontsize=8.5)
            ax.set_xticks(range(int(sub['stage'].max()) + 1))
            ax.set_ylim(bottom=0)
            ax.grid(axis='y', color='0.9', lw=0.6, zorder=-1)
            ax.tick_params(labelsize=8)
        handles = [Line2D([], [], color=COORD_COLOR, marker='o', ms=3, label=labels['coord']),
                   Line2D([], [], color=SELFISH_COLOR, marker='o', ms=3, label=labels['selfish']),
                   Line2D([], [], color='black', ls=':', lw=0.9, label='supply')]
        fig.legend(handles=handles, loc='outside upper center', ncol=3, fontsize=8.5)
        if out_path is not None:
            save_figure(fig, out_path)
    return fig


def plot_costs(tm: TutorialModel, data: TutorialData, out_path: str | Path | None = None, *,
               ns: Sequence[int] = (10, 100, 1000), figsize=(6.6, 2.5)) -> Figure:
    '''
    Left: extra cost of the selfish booths over the coordinator, in % of the coordinator's cost, against N (simulation,
    paired 95% intervals). Right: cumulative cars lost per booth, period by period, in the large-N limit (fluid).
    '''

    with rc_context(PAPER_RC):
        fig = Figure(figsize=figsize, layout='constrained')
        left, right = fig.subplots(1, 2)
        for mech, color, marker in (('M1', SELFISH_COLOR, 'o'), ('M2', CONGESTION_COLOR, 's')):
            xs, ys, es = [], [], []
            for N in ns:
                pr = paired_row(data, 'selfish_minus_coord', mech, N)
                coord = float(pop_row(data, 'coord', mech, N)['cost_mean'])
                xs.append(N)
                ys.append(100.0 * float(pr['diff_mean']) / coord)
                es.append(100.0 * float(pr['diff_ci95']) / coord)
            left.errorbar(xs, ys, yerr=es, color=color, marker=marker, ms=4, lw=1.2, capsize=2,
                          label=f'selfish, {MECH_WORDS[mech]}')
        left.axhline(0.0, color='black', lw=0.8)
        left.set_xscale('log')
        left.set_xticks(list(ns), [str(n) for n in ns])
        left.set_xlabel('number of booths $N$', fontsize=8.5)
        left.set_ylabel('extra cost vs coordinator (%)', fontsize=8.5)
        left.set_title('The price of no coordination', fontsize=9, pad=3)
        left.grid(color='0.9', lw=0.6, zorder=-1)
        left.tick_params(labelsize=8)
        left.legend(fontsize=7.5, loc='upper left')

        t = np.arange(tm.params.T)
        for key, color, marker, label in (('lp', COORD_COLOR, 'o', 'coordinator (LP plan)'),
                                          ('selfish_M1', SELFISH_COLOR, 'o', 'selfish, rationing'),
                                          ('selfish_M2', CONGESTION_COLOR, 's', 'selfish, congestion')):
            right.plot(t, np.cumsum(fluid_lost_cars(tm, key)), color=color, marker=marker, ms=3, label=label)
        right.set_xticks(t)
        right.set_xlabel('period $t$', fontsize=8.5)
        right.set_ylabel('cars lost per booth, cumulative', fontsize=8.5)
        right.set_title(r'Lost cars (large-$N$ limit)', fontsize=9, pad=3)
        right.grid(color='0.9', lw=0.6, zorder=-1)
        right.tick_params(labelsize=8)
        right.legend(fontsize=7.5, loc='upper left')
        if out_path is not None:
            save_figure(fig, out_path)
    return fig


