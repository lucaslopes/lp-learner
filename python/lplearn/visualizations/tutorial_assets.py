def plot_values(tm: TutorialModel, out_path: str | Path | None = None, *, figsize=(6.6, 2.5)) -> Figure:
    '''
    Backward induction for one booth on its own cost. Left: the optimal cost-to-go V_t(s) by period, one line per lane
    length. Right: the private gain of an attendant, Q_t(s, (a, 0)) - Q_t(s, (a, 1)) with the selfish gate decision a,
    for the lane lengths a booth can have at period t (s <= t).
    '''

    sol = tm.selfish
    T, S = sol.u.shape
    t = np.arange(T)
    fast = sol.fast_advantage()  # (T, S, 2) indexed by a
    gain = np.take_along_axis(fast, sol.a[:, :, None].astype(np.int64), axis=2)[:, :, 0]
    colors = [colormaps_ramp(s, S) for s in range(S)]
    with rc_context(PAPER_RC):
        fig = Figure(figsize=figsize, layout='constrained')
