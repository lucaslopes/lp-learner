@dataclass
class TutorialModel:
    '''
    The CJS instance with everything the tutorial derives from it without simulation.
    '''

    params: QueueParams
    model: WCMDP
    lp: dict
    pi_lp: np.ndarray                     # (T, S, U) coordinator's plan pi_t(u | s)
    selfish: PrivateSolution              # backward induction on the booth's own cost
    fluid: dict[str, dict] = field(default_factory=dict)  # 'lp', 'selfish_M1', 'selfish_M2' (N -> infinity)


def base_params(cfg: Mapping[str, Any] | None = None) -> QueueParams:
    '''
    The CJS parameters of the tutorial (defaults: the manuscript's base instance).
    '''

    cfg = dict(cfg or {})
    values = {k: cfg.get(k, DEFAULT_BASE[k]) for k in BASE_KEYS}
    return QueueParams(case='CJS', K=int(values['K']), T=int(values['T']), p=float(values['p']),
                       b_low=float(values['b_low']), b_high=float(values['b_high']), alpha=float(values['alpha']),
                       beta=float(values['beta']), gamma=float(values['gamma']), gamma_bar=float(values['gamma_bar']))


def solve_tutorial_model(params: QueueParams) -> TutorialModel:
    model = queue_wcmdp(params)
    lp = solve_method_a(model)
    pi_lp = conditional_policy(lp['y'])
    sol = selfish_solution(model, 'no_request')
    out = TutorialModel(params=params, model=model, lp=lp, pi_lp=pi_lp, selfish=sol)
    # The LP plan uses the budgets only in expectation, so in the fluid limit its requests never exceed them and every
    # mechanism serves them unchanged.
    out.fluid['lp'] = fluid_mechanism(params, model, pi_lp, 'M1')
    for mech in ('M1', 'M2'):
        out.fluid[f'selfish_{mech}'] = fluid_mechanism(params, model, deterministic_policy(sol.u), mech)
    return out


def fluid_lost_cars(tm: TutorialModel, key: str) -> np.ndarray:
    '''
    Cars lost per booth in each period in the large-N limit: alpha minus the realised admissions to lanes that are not
    full, sum_{s < K} m_s(t) pi(a = 1 | s) grant_a(t), for the fluid run `key` ('lp', 'selfish_M1', 'selfish_M2').
    '''

    fl = tm.fluid[key]
    K = tm.params.K
    pi_req = tm.pi_lp if key == 'lp' else deterministic_policy(tm.selfish.u)
    admit = (pi_req @ ADMIT) * fl['grant_a'][:, None]  # (T, S) realised admission probability
    served = np.sum(fl['mass'][:, :K] * admit[:, :K], axis=1)
    return tm.params.alpha - served


def per_period_departure_probability(p: float, q: float) -> float:
    '''
    Probability that a given car leaves during one period (Geometric(p) time steps, per-step probability q):
    1 - E[(1 - q)^tau] = q / (1 - (1 - p)(1 - q)).
    '''

    return q / (1.0 - (1.0 - p) * (1.0 - q))


