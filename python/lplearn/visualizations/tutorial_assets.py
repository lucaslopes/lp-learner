def selfish_occupation(tm: TutorialModel, mechanism: str = 'M1', realised: bool = True) -> np.ndarray:
    '''
    Large-N occupation measure y[t, s, u] of the selfish booths under `mechanism`: the fraction of booths in state s at
    period t that request (`realised` False) or end up with (`realised` True) action u, after the lotteries.
    '''

    fl = tm.fluid[f'selfish_{mechanism}']
    pi_req = deterministic_policy(tm.selfish.u)
    T, S, U = pi_req.shape
    y = np.zeros((T, S, U))
    for t in range(T):
        pi_t = realized_policy(pi_req[t], fl['grant_a'][t], fl['grant_b'][t], mechanism) if realised else pi_req[t]
        y[t] = fl['mass'][t][:, None] * pi_t
    return y


