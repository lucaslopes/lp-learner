MINUS = '\\ensuremath{-}'  # a true minus sign, in text and in math mode


def _f(x: float, digits: int = 1) -> str:
    if x is None or not math.isfinite(float(x)):
        return '--'
    value = round(float(x), digits)
    if value == 0:
        value = 0.0  # no "-0.0"
    text = f'{abs(value):.{digits}f}'
    return f'{MINUS}{text}' if value < 0 else text


def _signed(x: float, digits: int = 1) -> str:
    text = _f(x, digits)
    return text if text.startswith(MINUS) or text == '--' else f'+{text}'


def _pct_digits(x: float) -> int:
    '''One decimal, or two when the value would otherwise print as 0.0.'''
    return 2 if abs(float(x)) < 0.095 else 1


def _pm(mean: float, ci: float, digits: int = 1) -> str:
    if ci is None or not math.isfinite(float(ci)):
        return _f(mean, digits)
    return f'{_f(mean, digits)}\\,$\\pm$\\,{_f(ci, digits)}'


def _pm_signed(mean: float, ci: float, digits: int = 1) -> str:
    if ci is None or not math.isfinite(float(ci)):
        return _signed(mean, digits)
    return f'{_signed(mean, digits)}\\,$\\pm$\\,{_f(ci, digits)}'


def _pct(x: float, digits: int = 1) -> str:
    return _f(100.0 * x, digits)


