'''
Figures, tables and quoted numbers of the undergraduate tutorial (``papers/Tutorial/main.tex``).

The tutorial uses the CJS instance of the SIGMETRICS manuscript (Section 7 there) and its no-coordinator experiment.
Everything it shows comes from two sources:

- deterministic computations redone here from the model parameters: the transition kernel, the relaxed LP and its
  prices (method A, ``lplearn.commons.experiment.solve_method_a``), the selfish policy (backward induction,
  ``lplearn.commons.selfish``) and the N -> infinity (fluid) evaluation of both under a mechanism
  (``lplearn.commons.mechanisms.fluid_mechanism``);
- the recorded summaries of the experiment stages: ``commons`` run with ``configs/commons_tutorial.toml`` (summarized
  into ``results/commons/summary_tutorial``), ``finite_n`` (``results/finite_n/summary``) and the learned solutions of
  ``learners`` (``results/learners/summary/solutions_K5T10.npz``);
- one illustrative simulated run of N = 20 booths, redone here with the commons stage's random-number keys
  (``simulate_run``; its cost equals that of ``lplearn.commons.experiment`` for the same keys).

``build_assets`` writes the PDF figures, one LaTeX table per file and ``numbers.tex``, a list of ``\\newcommand``
macros for every number the text quotes, so that no number in the manuscript is typed by hand. The stage
``tutorial`` (``lplearn/experiments/stages/tutorial.py``) calls it.

Vocabulary of the tutorial (a pedagogical analogy, not a deployment claim): booth = queue (arm), cars in the lane =
queue length, open the gate = admission (a = 1), call a mobile attendant = high service rate (b = 1), platoon of
alpha N cars per period = admission budget, beta N attendants = high-rate budget, period = arrival epoch (stage).
'''


