def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for block in iter(lambda: handle.read(1 << 20), b''):
            digest.update(block)
    return digest.hexdigest()


def load_data(commons_dir: str | Path, finite_n_summary: str | Path) -> TutorialData:
    commons_dir = Path(commons_dir)
    paths = {
        'summary': commons_dir / 'commons_summary.csv',
        'paired': commons_dir / 'commons_paired.csv',
        'dilemma': commons_dir / 'commons_dilemma.csv',
        'stages': commons_dir / 'commons_stages.csv',
        'fluid': commons_dir / 'commons_fluid.csv',
        'finite_n': Path(finite_n_summary),
    }
    frames = {}
    for key, path in paths.items():
        if not path.is_file():
            raise TutorialInputError(f'missing input {path}; run and summarize the upstream stage first (see configs/tutorial.toml)')
        frames[key] = pd.read_csv(path)
    return TutorialData(**frames, files={str(path): _sha256(path) for path in paths.values()})


def _one(frame: pd.DataFrame, what: str, **match: Any) -> pd.Series:
    mask = np.ones(len(frame), dtype=bool)
    for column, value in match.items():
        if column not in frame.columns:
            raise TutorialInputError(f'{what}: column {column!r} missing')
        mask &= (frame[column].astype(str) == str(value)).to_numpy()
    rows = frame[mask]
    if len(rows) != 1:
        raise TutorialInputError(f'{what}: expected one row for {match}, found {len(rows)}')
    return rows.iloc[0]


def pop_row(data: TutorialData, population: str, mechanism: str, N: int, scenario: str = 'base',
            tie_break: str = 'no_request') -> pd.Series:
    return _one(data.summary, 'commons_summary', scenario=scenario, case='CJS', N=N, mechanism=mechanism,
                tie_break=tie_break, population=population)


def paired_row(data: TutorialData, comparison: str, mechanism: str, N: int, scenario: str = 'base',
               tie_break: str = 'no_request') -> pd.Series:
    return _one(data.paired, 'commons_paired', scenario=scenario, case='CJS', N=N, mechanism=mechanism,
                tie_break=tie_break, comparison=comparison)


def dilemma_row(data: TutorialData, test: str, mechanism: str, N: int, scenario: str = 'base',
                tie_break: str = 'no_request') -> pd.Series:
    return _one(data.dilemma, 'commons_dilemma', scenario=scenario, case='CJS', N=N, mechanism=mechanism,
                tie_break=tie_break, test=test)


def finite_n_row(data: TutorialData, method: str, policy: str, N: int) -> pd.Series:
    return _one(data.finite_n, 'finite_n_summary', case='CJS', method=method, policy=policy, N=N)


def lost_cars(row: pd.Series, params: QueueParams) -> float:
    '''
    Cars lost per booth over the horizon: alpha T cars arrive per booth on average; a booth that ends a period without
    a new car (not sent one, or sent one while full) accounts for one lost toll, of which (1 - alpha) T per booth are
    unavoidable because the platoon has only alpha N cars.
    '''

    return float(row['not_admitted_per_queue_horizon'] + row['blocked_per_queue_horizon'] - (1.0 - params.alpha) * params.T)


