'''
Stage ``figures``: the publication figures of the SIGMETRICS manuscript, drawn from recorded results.

The stage has one trivial job, because the figures are functions of the recorded results and of the options in
configs/figures.toml, not of job parameters. ``summarize`` redraws every requested figure each time it runs, into
``out_dir`` (papers/SIGMETRICS/figures/generated by default), so the PDFs always reflect the current results. It
writes ``figures_manifest.json`` (settings, input files with hashes, failures) into the stage summary directory.
If a figure's inputs are missing, the other figures are still drawn and ``summarize`` then fails with the reasons.

    lplearn experiments run figures --config configs/figures.toml
    lplearn experiments summarize figures --config configs/figures.toml
    lplearn experiments summarize figures --config configs/figures.toml --smoke    # into results/smoke/figures

Plotting and loading live in lp_learner/visualizations/paper_figures.py, which is imported lazily.
'''

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np

from lplearn.experiments.io import atomic_write_json
from lplearn.experiments.runner import StageError

NAME = 'figures'
VERSION = '2'  # preserve pre-existing PDFs on a failed redraw
SMOKE = {'results_root': 'results/smoke', 'out_dir': 'results/smoke/figures'}
MANIFEST_NAME = 'figures_manifest.json'


def _paper_figures():
    from lplearn.visualizations import paper_figures

    return paper_figures


def make_jobs(cfg: dict[str, Any]) -> list[dict[str, Any]]:
    '''
    One job that lists the figures to draw. Unknown figure names are refused here, before anything runs.
    '''

    known = _paper_figures().FIGURE_NAMES
    names = list(cfg.get('figures') or known)
    unknown = [name for name in names if name not in known]
    if unknown:
        raise StageError(f'unknown figure(s) {unknown}; known figures: {", ".join(known)}')
    return [{'figures': names}]


def run_job(job: dict[str, Any]) -> dict[str, Any]:
    '''
    Records which figures the job lists. The drawing happens in ``summarize``.
    '''

    names = [str(name) for name in job['figures']]
    return {'n_figures': len(names), 'figures': np.array(names, dtype=str)}


def summarize(records: list[tuple[dict[str, Any], dict[str, Any]]], cfg: dict[str, Any], out_dir: Path) -> None:
    '''
    Redraw the requested figures from the recorded results in ``cfg['results_root']`` into ``cfg['out_dir']``.
    Raises StageError after drawing the others if any figure could not be drawn.
    '''

    paper_figures = _paper_figures()
    try:
        settings, inputs = paper_figures.options_from_mapping(cfg)
    except (ValueError, KeyError, TypeError) as exc:
        raise StageError(f'figures: invalid options: {exc}') from exc
    results_root = Path(cfg.get('results_root', paper_figures.DEFAULT_RESULTS_ROOT))
    figure_dir = Path(cfg.get('out_dir', paper_figures.DEFAULT_OUT_DIR))
    names = list(settings.figures)

    run = paper_figures.build_figures(results_root, figure_dir, names=names, settings=settings, inputs=inputs)
    atomic_write_json(
        out_dir / MANIFEST_NAME,
        paper_figures.manifest(run, results_root=results_root, out_dir=figure_dir, settings=settings, inputs=inputs),
    )
    if run.failed:
        details = '; '.join(f'{name}: {message}' for name, message in run.failed.items())
        raise StageError(
            f'{len(run.failed)} of {len(names)} figure(s) not written ({len(run.written)} written; '
            f'{len(run.preserved)} previous PDF(s) preserved and not regenerated; manifest in {out_dir}): {details}'
        )
