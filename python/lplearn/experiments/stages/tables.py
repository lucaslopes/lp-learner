def lp_comparison_table(root: Path) -> str:
    rows = []
    for case in ('CJS', 'SJS'):
        df = _read(root / 'learners' / 'summary' / f'comparison_{case}.csv').set_index('label')
        rows.append(f'\\multicolumn{{8}}{{l}}{{\\textit{{{case}}}}} \\\\')
        for label in 'ABCDEFGHIJK':
            r = df.loc[label]
            learned = int(r['n_seeds']) > 1
            agg = r['aggregation_effect'] if label in 'EFGHIJK' else float('nan')
            r2r = r['run_to_run_y_mean'] if learned else float('nan')
            cells = [
                f'({label})',
                _pm(r['objective_mean'], r['objective_sd'] if learned else 0, 1),
                _num(r['gap_A_pct_mean'], 1),
                _num(r['mass_last_mean'], 2),
                _pm(r['dist_B_mean'], r['dist_B_sd'] if learned else 0, 2),
                _num(agg, 2),
                _num(r2r, 2) if learned else '--',
                _pm(r['lam_dist_B_mean'], r['lam_dist_B_sd'] if learned else 0, 1),
            ]
            rows.append(' & '.join(cells) + ' \\\\')
        rows.append('\\midrule')
    rows = rows[:-1]
    return HEADER + '\n'.join([
        '\\begin{table}[t]',
        '\\centering',
        '\\caption{LP-level comparison of methods (A)--(K) for $K=5$, $T=10$.  Learned methods report the tail average '
        '$\\bar y$ as mean\\,$\\pm$\\,sd over seeds (GDA: 3, SGDA: 10).  Gap: $c^\\top\\bar y$ relative to (A).  '
        '$m_{T-1}$: total mass at the last stage (1 for a feasible occupation measure).  Aggr.: '
        'aggregation effect $\\|\\bar y^\\star_{\\widehat\\cS}-y^\\star\\|_F$ between the exact aggregate and detailed '
        'saddle points, free of solver noise.  Run-to-run: mean Frobenius distance between independent seeds of the same '
        'configuration.  $\\|\\bar\\lambda-\\lambda^B\\|_2$: distance of the resource prices over all stages.}',
        '\\label{tab:lp-comparison}',
        '\\small',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\resizebox{\\linewidth}{!}{%',
        '\\begin{tabular}{lrrrrrrr}',
        '\\toprule',
        'Method & $c^\\top\\bar y$ & Gap [\\%] & $m_{T-1}$ & $\\|\\bar y-y^B\\|_F$ & Aggr. & Run-to-run & '
        '$\\|\\bar\\lambda-\\lambda^B\\|_2$ \\\\',
        '\\midrule',
        *rows,
        '\\bottomrule',
        '\\end{tabular}}',
        '\\end{table}',
        '',
    ])


