FINITE_N_ROWS = (
    [('A', 'projection', '(A) projection'), ('A', 'lp_update', '(A) LP update'), ('B', 'projection', '(B) projection'),
     ('C', 'projection', '(C) projection'), ('D', 'projection', '(D) projection')]
    + [row for label in 'EFGHIJK' for row in (
        (label, 'projection', f'({label}) SGDA, projection'),
        (f'{label}-LP', 'projection', f'({label}) LP, projection'),
        (f'{label}-LP', 'lp_update', f'({label}) LP, update'))]
)


def finite_n_table(root: Path) -> str:
    df = _read(root / 'finite_n' / 'summary' / 'finite_n_summary.csv')
    coordinated = df[df['policy'].isin(['projection', 'lp_update'])]
    violations = pd.to_numeric(coordinated['viol_max'], errors='coerce').to_numpy(dtype=float)
    if not len(violations) or not np.isfinite(violations).all() or np.any(violations < 0):
        raise StageError('finite_n: coordinated policy budget violations are missing or invalid')
    if float(violations.max()) > 0:
        raise StageError('finite_n: a coordinated policy violated a sample-path budget')
    Ns = sorted(int(n) for n in df['N'].unique())
    cases = ['CJS', 'SJS']
    lp = {case: float(df[df['case'] == case]['lp_objective'].iloc[0]) for case in cases}
    rows = ['LP value (A) & ' + ' & '.join(f'\\multicolumn{{{len(Ns)}}}{{c}}{{{lp[case]:.2f}}}' for case in cases)
            + ' \\\\', '\\midrule']
    for method, policy, text in FINITE_N_ROWS:
        cells = []
        for case in cases:
            for N in Ns:
                sel = df[(df['case'] == case) & (df['method'] == method) & (df['policy'] == policy) & (df['N'] == N)]
                if sel.empty:
                    cells.append('--')
                    continue
                row = sel.iloc[0]
                learned = int(row.get('n_seeds', 1)) > 1
                half = row['cost_ci95_seed'] if learned and 'cost_ci95_seed' in row else row['cost_ci95']
                cells.append(f'{row["cost_mean"]:.1f}\\,$\\pm$\\,{half:.1f}')
        rows.append(text + ' & ' + ' & '.join(cells) + ' \\\\')
        if method == 'D' or policy == 'lp_update' and method.endswith('-LP') and method[0] != 'K':
            rows.append('\\addlinespace[2pt]')
    reps = int(df['n_reps'].min())
    seeds = int(df['n_seeds'].max()) if 'n_seeds' in df else 1
    return HEADER + '\n'.join([
        '\\begin{table}[t]',
        '\\centering',
        f'\\caption{{Finite-$N$ cost per queue (sum over the $T$ stages) of feasible policies built from the LP solutions, '
        f'mean\\,$\\pm$\\,95\\% confidence half-width over {reps} replications with common random numbers; for the learned '
        'methods (C)--(K) the cost is averaged over the policies of all seeds (GDA: 3, SGDA: 10) and the interval is taken '
        'across seeds, so it includes the variation of the learned policies.  Projection: '
        'open-loop rounding of the LP policy with a greedy repair onto the budgets; update: the LP is re-solved from the '
        'empirical state at every stage~\\cite{lp-policy}.  All these policies satisfy both budgets on every sample path.}',
        '\\label{tab:finite-n}',
        '\\small',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\resizebox{\\linewidth}{!}{%',
        f'\\begin{{tabular}}{{l{"r" * (len(Ns) * len(cases))}}}',
        '\\toprule',
        ' & ' + ' & '.join(f'\\multicolumn{{{len(Ns)}}}{{c}}{{{case}}}' for case in cases) + ' \\\\',
        ''.join(f'\\cmidrule(lr){{{2 + i * len(Ns)}-{1 + (i + 1) * len(Ns)}}}' for i in range(len(cases))),
        'Policy & ' + ' & '.join(f'$N={n}$' for _ in cases for n in Ns) + ' \\\\',
        '\\midrule',
        *rows,
        '\\bottomrule',
        '\\end{tabular}}',
        '\\end{table}',
        '',
    ])


