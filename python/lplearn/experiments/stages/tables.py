COMMONS_ROWS = (
    ('coord', 'M1', 'Coordinated (LP projection)', '--'),
    ('indep', 'M0', 'Independent LP policy', 'none'),
    ('indep', 'M1', 'Independent LP policy', 'rationing'),
    ('selfish', 'M0', 'Selfish (private DP)', 'none'),
    ('selfish', 'M1', 'Selfish (private DP)', 'rationing'),
    ('selfish', 'M2', 'Selfish (private DP)', 'congestion'),
)


def commons_table(root: Path, N: int = 1000, scenario: str = 'base', tie: str = 'no_request') -> str:
    summary = _read(root / 'commons' / 'summary' / 'commons_summary.csv')
    paired = _read(root / 'commons' / 'summary' / 'commons_paired.csv')
    rows = []
    for case in ('CJS', 'SJS'):
        rows.append(f'\\multicolumn{{8}}{{l}}{{\\textit{{{case}}}}} \\\\')
        for pop, mech, text, enforcement in COMMONS_ROWS:
            sel = summary[(summary['scenario'] == scenario) & (summary['case'] == case) & (summary['N'] == N)
                          & (summary['mechanism'] == mech) & (summary['tie_break'] == tie) & (summary['population'] == pop)]
            if len(sel) != 1:
                raise StageError(f'commons: expected one row for {case}/{N}/{mech}/{pop}, got {len(sel)}')
            r = sel.iloc[0]
            if pop == 'coord':
                diff = '--'
            else:
                d = paired[(paired['scenario'] == scenario) & (paired['case'] == case) & (paired['N'] == N)
                           & (paired['mechanism'] == mech) & (paired['tie_break'] == tie)
                           & (paired['comparison'] == f'{pop}_minus_coord')].iloc[0]
                diff = f'{d["diff_mean"]:+.1f}\\,$\\pm$\\,{d["diff_ci95"]:.1f} ({d["pct_of_coord"]:+.1f}\\%)'
            rows.append(' & '.join([
                text, enforcement, f'{100 * r["overload_admit"]:.0f}', f'{100 * r["overload_fast"]:.0f}',
                f'{r["excess_fast_mean"]:.2f}', f'{r["cost_mean"]:.1f}\\,$\\pm$\\,{r["cost_ci95"]:.1f}', diff,
                f'{100 * r["full_mean_per_stage"]:.1f}',
            ]) + ' \\\\')
        rows.append('\\midrule')
    rows = rows[:-1]
    reps = int(summary[(summary['N'] == N) & (summary['scenario'] == scenario)]['reps'].min())
    return HEADER + '\n'.join([
        '\\begin{table}[t]',
        '\\centering',
        f'\\caption{{Coordinated and uncoordinated queues, $N={N}$, $K=5$, $T=10$, {reps} replications with common random '
        'numbers.  Overload: share of (replication, stage) pairs in which the requests exceed $\\lfloor\\alpha N\\rfloor$ '
        '(admission) or $\\lfloor\\beta N\\rfloor$ (fast mode).  Excess: mean of $(D_b/N-\\beta)_+$ for the fast mode.  '
        'Enforcement: none (requests are served, budgets are exceeded), rationing (a uniformly random subset of '
        'requesters of the budget size is served), or congestion (admissions are rationed and the fast capacity is '
        'shared among its requesters).  Cost: model cost per queue over the horizon, mean\\,$\\pm$\\,95\\% half-width; '
        '$\\Delta$: paired difference with the coordinated policy.  Full: average share of full queues.}',
        '\\label{tab:commons}',
        '\\small',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\resizebox{\\linewidth}{!}{%',
        '\\begin{tabular}{llrrrrrr}',
        '\\toprule',
        ' & & \\multicolumn{2}{c}{Overload [\\%]} & & & & \\\\',
        '\\cmidrule(lr){3-4}',
        'Population & Enforcement & adm. & fast & Excess & Cost & $\\Delta$ vs coordinated & Full [\\%] \\\\',
        '\\midrule',
        *rows,
        '\\bottomrule',
        '\\end{tabular}}',
        '\\end{table}',
        '',
    ])


BUILDERS = {'lp_comparison': lp_comparison_table, 'bound': bound_table, 'finite_n': finite_n_table,
            'commons': commons_table}


def summarize(records: list[tuple[dict[str, Any], dict[str, Any]]], cfg: dict[str, Any], out_dir: Path) -> None:
    '''Write every requested table into cfg['out_dir'] and a manifest of inputs into the stage summary directory.'''
    root = Path(cfg.get('results_root', 'results'))
    target = Path(cfg['out_dir']) if 'out_dir' in cfg else Path(out_dir)
    rendered, failed = {}, {}
    for name in cfg.get('tables', TABLES):
        builder = BUILDERS.get(name)
        if builder is None:
            failed[name] = 'no builder'
            continue
        try:
            rendered[name] = builder(root)
        except (FileNotFoundError, IndexError, KeyError, ValueError, StageError) as exc:
            failed[name] = str(exc)
    if failed:
        atomic_write_json(Path(out_dir) / 'tables_manifest.json', {'results_root': str(root), 'out_dir': str(target),
                                                                   'written': [], 'failed': failed})
        raise StageError(f'tables not written: {failed}')
    target.mkdir(parents=True, exist_ok=True)
    for name, contents in rendered.items():
        atomic_write_text(target / f'{name}.tex', contents)
    atomic_write_json(Path(out_dir) / 'tables_manifest.json', {'results_root': str(root), 'out_dir': str(target),
                                                               'written': list(rendered), 'failed': {}})
