'''
Stage ``tables``: the manuscript tables of Section 8, generated from the recorded summaries of the other stages.

The stage has a single trivial job; ``summarize`` reads the CSV summaries under ``results_root`` and writes one
LaTeX table per file into the runner's summary directory, unless ``out_dir`` is explicitly configured. No number is typed by hand:
rerun ``lplearn experiments summarize tables --config configs/tables.toml`` after any upstream stage changes.

Inputs (relative to ``results_root``):
- learners/summary/comparison_{CJS,SJS}.csv  (stage ``learners``)
- bound/summary/bound_rows.csv              (stage ``bound``)
- finite_n/summary/finite_n_summary.csv, finite_n_paired.csv (stage ``finite_n``)
- commons/summary/commons_summary.csv, commons_paired.csv, commons_dilemma.csv (stage ``commons``)
'''


from __future__ import annotations

import math
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from lplearn.experiments.io import atomic_write_json, atomic_write_text
from lplearn.experiments.runner import StageError


NAME = 'tables'
VERSION = '2'  # safe default destination and all-tables validation before writing
TABLES = ('lp_comparison', 'bound', 'finite_n', 'commons')
HEADER = '% Generated by `lplearn experiments summarize tables` from recorded results; do not edit by hand.\n'


def make_jobs(cfg: dict[str, Any]) -> list[dict[str, Any]]:
    names = cfg.get('tables', TABLES)
    if not isinstance(names, (list, tuple)) or not names or any(name not in TABLES for name in names):
        raise StageError(f'tables must be a nonempty list drawn from {TABLES}')
    if len(set(names)) != len(names):
        raise StageError('tables must not contain duplicate names')
    return [{'tables': list(names)}]


def run_job(job: dict[str, Any]) -> dict[str, Any]:
    return {'n_tables': len(job['tables'])}


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def _num(x: float, digits: int = 2) -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return '--'
    return f'{x:.{digits}f}'


def _pm(mean: float, sd: float, digits: int = 2) -> str:
    if sd is None or not math.isfinite(sd) or sd == 0:
        return _num(mean, digits)
    return f'{mean:.{digits}f}\\,$\\pm$\\,{sd:.{digits}f}'


def _sci(x: float) -> str:
    if not math.isfinite(x):
        return '--'
    if abs(x) >= 1e4:
        mant, exp = f'{x:.1e}'.split('e')
        return f'${mant}\\cdot10^{{{int(exp)}}}$'
    if abs(x) >= 100:
        return f'{x:.0f}'
    if abs(x) >= 10:
        return f'{x:.1f}'
    return f'{x:.2f}'


def _read(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f'missing input {path}; run and summarize the upstream stage first')
    return pd.read_csv(path)


