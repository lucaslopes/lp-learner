def bound_table(root: Path) -> str:
    df = _read(root / 'bound' / 'summary' / 'bound_rows.csv')
    df = df[(df['K'] == 5) & (df['T'] == 10)]

    def pick(case, label, regime, convention):
        sel = df[(df['case'] == case) & (df['label'] == label) & (df['regime'] == regime) & (df['convention'] == convention)]
        if len(sel) != 1:
            raise StageError(f'bound: expected one row for {case}/{label}/{regime}/{convention}, got {len(sel)}')
        return sel.iloc[0]

    rows = []
    for label in 'EFGHIJK':
        lem = pick('CJS', label, 'lemma2', 'consistent')
        lit = pick('CJS', label, 'lemma2', 'paper')
        exp = pick('CJS', label, 'grid2e-05', 'consistent')
        sjs = pick('SJS', label, 'lemma2', 'consistent')
        terms = (lem['B_spec'], lem['dist_total'], exp['B_spec'], exp['dist_total'])
        if not all(math.isfinite(x) for x in terms) or not (terms[0] >= terms[1] - 1e-9 and terms[2] >= terms[3] - 1e-9):
            raise StageError(f'bound: spectral bound is non-finite or below observed distance for {label}')
        rows.append(' & '.join([
            f'({label})', _sci(lem['delta_c']), _num(lem['delta_P'], 2), _num(sjs['delta_P'], 2), _num(lem['delta_0'], 0),
            _sci(lem['dist_total']), _sci(lem['B_spec']), _sci(lem['B_lemma1']), _sci(lit['dist_total']),
            _sci(exp['dist_total']), _sci(exp['B_spec']),
        ]) + ' \\\\')
    kappa = float(df[(df['case'] == 'CJS') & (df['regime'] == 'lemma2')]['kappa_max'].iloc[0])
    return HEADER + '\n'.join([
        '\\begin{table}[t]',
        '\\centering',
        '\\caption{Aggregation bound for partitions (E)--(K), CJS, $K=5$, $T=10$ (the $\\delta$ terms of SJS are shown '
        'for $\\delta_P$ only; its bound columns behave the same way).  Lemma regime: '
        f'$\\Gamma_y=\\Gamma_\\lambda=\\Gamma_\\mu=2\\kappa={2 * kappa:.2f}$, where Lemma~\\ref{{lem:contraction}} holds with '
        '$c_G=0.5$.  Experimental regime: $\\Gamma_y=1$, $\\Gamma_\\lambda=\\Gamma_\\mu=2\\cdot10^{-5}$, where it does '
        'not.  $\\|w^*-\\overline w^*\\|$: true distance for the lifted operator~\\eqref{eq:lifted-operator}; '
        '$B_{\\mathrm{sp}}$: bound of Theorem~\\ref{thm:main-bound} with the spectral contraction constant '
        '$\\|I-\\eta(R+S)\\|_2$; $B_{\\mathrm{L1}}$: the same with $c_G$ of Lemma~\\ref{lem:contraction}; literal: true '
        'distance when the multipliers are lifted by $U$, as in the original definition.}',
        '\\label{tab:bound}',
        '\\small',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\resizebox{\\linewidth}{!}{%',
        '\\begin{tabular}{lrrrrrrrrrr}',
        '\\toprule',
        ' & & \\multicolumn{2}{c}{$\\delta_P$} & & \\multicolumn{4}{c}{Lemma regime} & \\multicolumn{2}{c}{Experimental regime} \\\\',
        '\\cmidrule(lr){3-4}\\cmidrule(lr){6-9}\\cmidrule(lr){10-11}',
        'Partition & $\\delta_c$ & CJS & SJS & $\\delta_0$ & $\\|w^*-\\overline w^*\\|$ & $B_{\\mathrm{sp}}$ & '
        '$B_{\\mathrm{L1}}$ & literal & $\\|w^*-\\overline w^*\\|$ & $B_{\\mathrm{sp}}$ \\\\',
        '\\midrule',
        *rows,
        '\\bottomrule',
        '\\end{tabular}}',
        '\\end{table}',
        '',
    ])


